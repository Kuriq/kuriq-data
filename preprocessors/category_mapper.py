CATEGORY_MAP = {
    "IT·데이터": ["컴퓨터", "소프트웨어", "데이터", "인공지능", "정보통신", "IT", "코딩", "프로그래밍"],
    "경영·경제": ["경영", "경제", "회계", "금융", "마케팅", "창업"],
    "인문·교양": ["인문", "철학", "역사", "문학", "심리", "교양"],
    "외국어": ["영어", "중국어", "일본어", "외국어", "어학"],
    "자연과학·공학": ["수학", "물리", "화학", "생물", "공학", "기계", "전기", "건축"],
    "의료·보건": ["의학", "간호", "보건", "의료", "약학", "복지"],
    "예술·문화": ["예술", "음악", "미술", "디자인", "문화", "영상", "사진"],
    "사회·법": ["사회", "법", "행정", "정치", "교육", "복지"],
    "취미·생활": ["요리", "여행", "스포츠", "건강", "취미", "생활", "원예"],
}


def normalize_category(raw: str) -> str:
    """원본 카테고리 텍스트 -> 큐릭 표준 카테고리"""
    if not raw:
        return "기타"
    for std_cat, keywords in CATEGORY_MAP.items():
        for kw in keywords:
            if kw in raw:
                return std_cat
    return "기타"